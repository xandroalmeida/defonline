    <li><strong>Uso:</strong> eventos de uso sem informações pessoais identificáveis, para análise agregada, e registros de acesso e auditoria.</li>
</ul>

<h2>2. Bases legais (LGPD Art. 7º)</h2>
<ul>
    <li><strong>Execução de contrato</strong> (Art. 7º, V): criar e operar sua conta, prestar o serviço, cobrar e enviar comunicações transacionais.</li>
    <li><strong>Consentimento</strong> (Art. 7º, I): comunicações de marketing opcionais, que você pode aceitar ou recusar a qualquer momento.</li>
    <li><strong>Obrigação legal ou regulatória</strong> (Art. 7º, II): registros fiscais e outros exigidos por lei.</li>
    <li><strong>Legítimo interesse</strong> (Art. 7º, IX): segurança, prevenção a fraude e uso de dados anonimizados em estudos, medianas setoriais e evolução do produto.</li>
</ul>

<h2>3. Compartilhamento</h2>
<p>Não vendemos dados a terceiros. Compartilhamos apenas o necessário com:</p>
<ul>
    <li><strong>Asaas</strong>, provedor de pagamento: a descrição e o valor da cobrança e o código interno da compra, quando você contrata um plano ou pacote. O DEFOnline não envia seu nome, CPF ou e-mail ao provedor: os dados do cartão e os de identificação que o provedor exigir, você os informa diretamente na página de pagamento do provedor. Do provedor recebemos a confirmação do pagamento, a bandeira e os quatro últimos dígitos do cartão.</li>
    <li><strong>Provedores de infraestrutura:</strong> hospedagem, backup e e-mail transacional.</li>
    <li><strong>Provedores de consulta à Receita Federal:</strong> o CNPJ informado no cadastro da empresa.</li>
    <li><strong>Autoridades:</strong> quando exigido por lei ou ordem judicial.</li>
</ul>
<p>Alguns provedores podem processar dados fora do Brasil, com as salvaguardas previstas na LGPD.</p>

<h2>4. Acesso da equipe</h2>
<p>A equipe autorizada da EB Parcerias pode acessar dados da conta para suporte e operação da plataforma. Esses acessos são restritos e registrados.</p>

<h2>5. Direitos do titular</h2>
<p>Você pode solicitar acesso, correção, anonimização, portabilidade, eliminação dos dados ou revogação do consentimento, escrevendo para <a href="mailto:dpo@ebparcerias.com">dpo@ebparcerias.com</a>. Respondemos em até 15 dias, prazo que pode chegar a 30 dias em pedidos complexos.</p>

<h2>6. Retenção</h2>
<p>Dados pessoais são mantidos enquanto a conta estiver ativa. Após pedido de exclusão, os dados identificáveis são anonimizados em 30 dias. Registros fiscais, financeiros e de auditoria são mantidos pelos prazos legais. Diagnósticos anonimizados podem ser mantidos para compor medianas setoriais.</p>

<h2>7. Segurança</h2>
<p>Adotamos medidas técnicas e administrativas para proteger seus dados, incluindo criptografia em trânsito, controle de acesso e registro de auditoria.</p>

<h2>8. Cookies</h2>
<p>Usamos apenas cookies necessários ao funcionamento da plataforma, como os de sessão e segurança. Não usamos cookies de publicidade nem de analytics de terceiros.</p>

<h2>9. Alterações</h2>
<p>Esta Política é versionada. Alterações relevantes são comunicadas e, quando exigido, dependem de novo aceite.</p>

<h2>10. Aceite</h2>
<p>Seu aceite é registrado com data, IP e hash do conteúdo desta versão.</p>
